"""Build the Time machine's scenarios from Binance daily closes.

    python scripts/build_replay.py

Writes two files that must stay in step (tests/test_replay.py checks them):

* ``server/data/replay.json``: the real closes, the coins' names and the dates.
  The server uses it to work out a finished game and to reveal what it was.
* ``frontend/src/lib/replayData.ts``: the same prices as an index that starts
  at 100 on day 0, under the letters A to D. No name and no date, so the game
  in the browser is blind.

A scenario is ``PRE`` days of run-up (shown on the chart, not playable),
day 0, then ``DAYS`` days to play. Prices are daily closes in UTC.
"""

from __future__ import annotations

import calendar
import json
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import requests  # noqa: E402

from advisor_engine import BINANCE_API  # noqa: E402

PRE = 7
DAYS = 30
DAY_MS = 86_400_000

# The ids say nothing about what happens: the app shows "Trip 1" and "Trip 2".
# One month with a crash, one with a rally, so staying in cash is right in one
# and wrong in the other. Letters are mixed so Bitcoin is not always "A".
SCENARIOS = [
    {
        "id": "m1",
        "event": "ftx",
        "from": date(2022, 10, 25),
        "coins": [("A", "ETH"), ("B", "DOGE"), ("C", "BTC"), ("D", "SOL")],
    },
    {
        "id": "m2",
        "event": "rally24",
        "from": date(2024, 11, 4),
        "coins": [("A", "SOL"), ("B", "BTC"), ("C", "XRP"), ("D", "DOGE")],
    },
]

JSON_OUT = ROOT / "server" / "data" / "replay.json"
TS_OUT = ROOT / "frontend" / "src" / "lib" / "replayData.ts"


def closes(base: str, first: date, count: int) -> list[float]:
    start_ms = calendar.timegm(first.timetuple()) * 1000
    resp = requests.get(
        f"{BINANCE_API}/api/v3/klines",
        params={"symbol": f"{base}USDT", "interval": "1d", "limit": count, "startTime": start_ms},
        timeout=30,
    )
    resp.raise_for_status()
    rows = resp.json()
    if len(rows) != count or any(rows[i][0] != start_ms + i * DAY_MS for i in range(count)):
        raise SystemExit(f"{base}: expected {count} daily candles from {first}, got {len(rows)}")
    return [float(r[4]) for r in rows]


def index(series: list[float]) -> list[float]:
    """Prices from a base of 100 on day 0. ``server/replay.py`` rounds the same way."""
    return [round(x / series[PRE] * 100, 4) for x in series]


def main() -> None:
    built = []
    for sc in SCENARIOS:
        first = sc["from"] - timedelta(days=PRE)
        coins = [{"key": key, "base": base, "closes": closes(base, first, PRE + DAYS + 1)} for key, base in sc["coins"]]
        built.append({"id": sc["id"], "event": sc["event"], "from": sc["from"].isoformat(), "pre": PRE, "days": DAYS, "coins": coins})
        for c in coins:
            print(f"{sc['id']} {c['key']} {c['base']:5} ends at {index(c['closes'])[-1]:.1f}", file=sys.stderr)

    JSON_OUT.write_text(
        json.dumps({"source": "Binance daily closes, UTC", "scenarios": built}, indent=1) + "\n", encoding="utf-8", newline="\n"
    )

    blind = [
        {"id": sc["id"], "days": sc["days"], "pre": sc["pre"], "coins": [{"key": c["key"], "index": index(c["closes"])} for c in sc["coins"]]}
        for sc in built
    ]
    lines = [
        "// GENERATED by scripts/build_replay.py. Do not edit by hand.",
        "//",
        "// The Time machine's scenarios as the browser sees them: prices from a base",
        "// of 100 on day 0, under letters. No name and no date: those stay on the",
        "// server (server/data/replay.json) until a game is finished.",
        "// No imports here, so the engine can be checked outside the app (tests/test_replay.py).",
        "",
        "export const REPLAYS = " + json.dumps(blind, indent=2),
        "",
    ]
    TS_OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {JSON_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
