// Export every Darija string of the Learn section to docs/learn/darija-review.md
// so it can be read and approved before release.
//   npm run learn:darija        (needs Node 22.18+ to import .ts directly)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..', '..')
const { LESSONS, LEVELS, GLOSSARY, LEARN_UI, isReady } = await import('../src/lib/lessons.ts')

const out = []
let n = 0
const item = (label, text) => {
  n += 1
  out.push(`- [ ] **${n}. ${label}** · _${text.en}_  `, `  ${text.ar}`, '')
}

out.push(
  '# Learn section: Arabic review',
  '',
  'Every Arabic text shown in the Learn section and the Telegram `/learn` command.',
  'Lessons, glossary and Learn screen are in light Arabic for all Arab countries (since 14 Nov 2026);',
  '`nav.learn` and the Telegram strings still follow the app’s Tunisian Darija.',
  'Tick each line once the wording and the words in Latin script are right.',
  '',
  'Generated by `npm run learn:darija` from `frontend/src/lib/lessons.ts` (Learn screen, level names),',
  '`frontend/src/lib/lessons/*.ts` (lesson text by level, glossary), `frontend/src/lib/i18n.ts` (`nav.learn`)',
  'and `server/telegram_bot.py` (`LEARN_T`, `LEARN_LESSONS`).',
  'Edit those files, not this one, then run the script again.',
  '',
)

let level = 0
LESSONS.forEach((l, i) => {
  const no = i + 1
  if (l.level !== level) {
    level = l.level
    const lv = LEVELS.find((v) => v.level === level)
    out.push(`# Level ${level}: ${lv.name.en}`, '')
    item(`Level ${level} name`, lv.name)
    item(`Level ${level} description`, lv.about)
  }
  out.push(`## Lesson ${no}: ${l.title.en} (\`#learn-${l.slug}\`)${isReady(l) ? '' : ' · outline'}`, '')
  item(`L${no} title`, l.title)
  item(`L${no} hook`, l.hook)
  l.sections?.forEach((s, j) => {
    item(`L${no} section ${j + 1} heading`, s.h)
    item(`L${no} section ${j + 1} text`, s.p)
  })
  if (l.takeaway) item(`L${no} takeaway`, l.takeaway)
  l.quiz?.forEach((q, j) => {
    item(`L${no} Q${j + 1}`, q.q)
    q.options.forEach((o, k) => item(`L${no} Q${j + 1} option ${'ABC'[k]}${k === q.answer ? ' ✓' : ''}`, o))
    item(`L${no} Q${j + 1} explanation`, q.why)
  })
  l.outline?.forEach((o, j) => item(`L${no} outline ${j + 1}`, o))
  if (l.live?.kind === 'view') item(`L${no} live button`, l.live.label)
})

out.push('## Glossary', '')
for (const [id, e] of Object.entries(GLOSSARY)) {
  item(`${id}: term`, e.term)
  item(`${id}: definition`, e.def)
}

out.push('## Learn screen', '')
const i18n = readFileSync(resolve(root, 'frontend/src/lib/i18n.ts'), 'utf8')
const nav = i18n.match(/'nav\.learn': \{ en: '([^']*)', fr: '([^']*)', ar: '([^']*)' \}/)
if (nav) item('nav.learn (top bar and bottom bar)', { en: nav[1], fr: nav[2], ar: nav[3] })
for (const [key, text] of Object.entries(LEARN_UI)) item(key, text)

out.push('## Telegram `/learn`', '')
const bot = readFileSync(resolve(root, 'server/telegram_bot.py'), 'utf8')
const block = bot.split('# LEARN-DARIJA-START')[1]?.split('# LEARN-DARIJA-END')[0] ?? ''
const pyStr = (s) => s.replace(/\\n/g, ' ⏎ ')
for (const m of block.matchAll(/\("([\w-]+)", \{"en": "([^"]*)", "fr": "([^"]*)", "ar": "([^"]*)"\}\)/g))
  item(`bot lesson title ${m[1]}`, { en: m[2], ar: m[4] })
const lang = (code) => block.split(`"${code}": {`)[1]?.split('},')[0] ?? ''
for (const key of ['learn_text', 'learn_btn', 'learn_all']) {
  const get = (code) => lang(code).match(new RegExp(`"${key}": "([^"]*)"`))?.[1] ?? ''
  item(`bot ${key}`, { en: pyStr(get('en')), ar: pyStr(get('ar')) })
}

const target = resolve(root, 'docs/learn/darija-review.md')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, out.join('\n'), 'utf8')
console.log(`wrote ${n} Arabic strings to docs/learn/darija-review.md`)
